/**
 * Компании с юридической формой ООО (рус.) / ҶДММ (тадж. эквивалент, «Ҷамъияти
 * дорои масъулияти маҳдуд») по решению C&B не участвуют в обзоре рынка.
 *
 * Фильтр применяется ТОЛЬКО на выдаче — строки в competitors / surveys остаются
 * в базе нетронутыми, чтобы решение откатывалось правкой одного этого файла, а
 * не обратной миграцией данных.
 *
 * Форму ищем отдельным «словом»: с начала строки или после пробела/кавычки/
 * скобки, чтобы не цеплять её внутри других слов. Флаг i покрывает и «ооо», и
 * «ҷдмм».
 */
const HIDDEN_FORM_RE = /(^|[\s"«»().,])(ООО|ҶДММ)([\s"«»().,]|$)/i;

function isHiddenCompany(name) {
  return HIDDEN_FORM_RE.test(String(name || ''));
}

module.exports = { isHiddenCompany };
