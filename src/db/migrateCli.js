'use strict';

// Прогон идемпотентных миграций схемы на этапе сборки Vercel
// (`npm run vercel-build`). На Render миграции запускал сам процесс при старте;
// на Vercel долгоживущего процесса нет, поэтому основной прогон — здесь, один
// раз на деплой, в детерминированном окружении сборки (без гонок холодного
// старта и без задержки на первом запросе).
//
// Сбой не должен ронять деплой: транзиентная недоступность Turso не повод
// откатывать выкатку кода. Миграции идемпотентны и аддитивны, а bootstrap()
// в src/server.js повторит их лениво на первом инстансе функции.
require('./migrate')
  .migrate()
  .then(() => {
    console.log('✅ vercel-build: идемпотентные миграции схемы применены');
    process.exit(0);
  })
  .catch((err) => {
    console.error('⚠️ vercel-build: миграции не удались (не фатально для деплоя):', err.message);
    process.exit(0);
  });
