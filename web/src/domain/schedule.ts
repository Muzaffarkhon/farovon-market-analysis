/**
 * Подпись графика работы для людей. В справочнике график хранится как
 * «5/2 · 40 часов» — по часам в неделю его сравнивает аналитика, и значение
 * не меняем. Показываем же время работы: «5/2 · 08:00–17:00» понятнее, чем
 * «40 часов». Время — типовое для такой недели при обеденном часе, как
 * подсказка в старом клиенте (SCHEDULE_HOURS в client/app.js).
 * У сменного, вахтового и свободного графика фиксированного времени нет —
 * они остаются как есть.
 */
const WORK_HOURS: Record<string, string> = {
  '5/2 · 40 часов': '08:00–17:00',
  '5/2 · 45 часов': '08:00–18:00',
  '6/1 · 48 часов': '09:00–18:00',
  '6/1 · 50 часов': '08:00–17:20',
  '6/1 · 54 часа': '08:00–18:00'
};

export function scheduleLabel(value: string): string {
  const hours = WORK_HOURS[value];
  if (!hours) return value;
  return `${value.split(' · ')[0]} · ${hours}`;
}
